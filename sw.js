/* LifeOS service worker — offline after first load.
 * Versioned cache: bump CACHE_VERSION on every deploy. IndexedDB is never
 * touched by the cache swap, so user data survives updates.
 *
 * NOTE (deploy): the Vite build step should regenerate PRECACHE_URLS with the
 * hashed asset names from dist/. This file's list covers the unhashed shell;
 * keep both in sync at deploy time (see WS-C-README.md).
 */
const CACHE_VERSION = 'lifeos-v1';
const CACHE_NAME = `lifeos-shell-${CACHE_VERSION}`;

// App shell: served cache-first so the app boots offline after first load.
const PRECACHE_URLS = /* auto-generated by scripts/patch-sw.mjs */ [
  "./",
  "./index.html",
  "./manifest.webmanifest",
  "./icons/apple-touch-icon.png",
  "./icons/icon-192.png",
  "./icons/icon-512.png",
  "./icons/icon-maskable-512.png",
  "./assets/api-CHwU-dIC.js",
  "./assets/calendar-z1JUAS62.js",
  "./assets/dayShell-BZ5EQiEi.js",
  "./assets/dom-CIBhK-3k.js",
  "./assets/feedback-DK-uWt75.js",
  "./assets/index-CU9fOGdj.css",
  "./assets/index-Co4kIumx.js",
  "./assets/quarter-Dg4LLLc_.js",
  "./assets/settings-2aRQuE28.js",
  "./assets/week-CUlO74QN.js",
  "./assets/year-ChVIQYdG.js"
];

self.addEventListener('install', (event) => {
  event.waitUntil(
    caches
      .open(CACHE_NAME)
      .then((cache) => cache.addAll(PRECACHE_URLS))
      .then(() => self.skipWaiting()),
  );
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches
      .keys()
      .then((keys) => Promise.all(keys.filter((k) => k !== CACHE_NAME).map((k) => caches.delete(k))))
      .then(() => self.clients.claim()),
  );
});

self.addEventListener('message', (event) => {
  if (event.data && event.data.type === 'SKIP_WAITING') self.skipWaiting();
});

self.addEventListener('fetch', (event) => {
  const { request } = event;
  if (request.method !== 'GET') return;
  const url = new URL(request.url);
  // Never cache cross-origin API calls (Google Calendar etc.).
  if (url.origin !== self.location.origin) return;
  event.respondWith(
    caches.match(request, { ignoreSearch: true }).then((cached) => {
      if (cached) return cached;
      return fetch(request).then((res) => {
        // Runtime-cache same-origin GETs for offline resilience.
        if (res.ok && (url.pathname.endsWith('.js') || url.pathname.endsWith('.css'))) {
          const copy = res.clone();
          caches.open(CACHE_NAME).then((cache) => cache.put(request, copy));
        }
        return res;
      });
    }),
  );
});
